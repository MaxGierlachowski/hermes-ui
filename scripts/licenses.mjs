#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.md: every production dependency of the backend, the web UI and the mobile
// app (npm) and of the iroh library (Cargo), with version and license, grouped by license.
//   node scripts/licenses.mjs            (after npm ci in the root and in mobile-app/)
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const rows = new Map() // "name@version" → { name, version, license, where:Set }

function add(name, version, license, where) {
  const key = `${name}@${version}`
  const row = rows.get(key) || { name, version, license: license || 'UNKNOWN', where: new Set() }
  row.where.add(where)
  rows.set(key, row)
}

// npm: production dependencies from `npm ls --omit=dev --all --json`, licenses from each package.json.
function npm(dir, where, workspace) {
  const args = ['ls', '--omit=dev', '--all', '--json', ...(workspace ? ['-w', workspace] : [])]
  let tree
  try { tree = JSON.parse(execFileSync('npm', args, { cwd: dir, encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] })) } catch (e) { tree = JSON.parse(e.stdout || '{}') }
  const walk = (deps) => {
    for (const [name, d] of Object.entries(deps || {})) {
      if (!d.version || d.extraneous) continue
      let license = ''
      const pj = d.path && path.join(d.path, 'package.json')
      if (pj && fs.existsSync(pj)) { const p = JSON.parse(fs.readFileSync(pj, 'utf8')); license = typeof p.license === 'string' ? p.license : p.license?.type || (p.licenses || []).map((l) => l.type || l).join(' OR ') }
      if (!name.startsWith('@hermes-ui/')) add(name, d.version, license, where)
      walk(d.dependencies)
    }
  }
  const top = workspace ? Object.values(tree.dependencies || {}).find((x) => x.resolved?.includes(workspace) || x.path?.endsWith(workspace))?.dependencies ?? tree.dependencies : tree.dependencies
  walk(top)
}
// npm ls -w gives the workspace's tree with "path"; long mode is needed for paths.
const ls = (dir, where, ws) => npm(dir, where, ws)
process.env.npm_config_long = 'true'
ls(root, 'server', 'server')
ls(root, 'web', 'web')
ls(path.join(root, 'mobile-app'), 'mobile-app')

// Cargo: the iroh library (mobile-app/modules/expo-iroh/rust), without dev/build-only crates of the host tools.
try {
  const meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], { cwd: path.join(root, 'mobile-app/modules/expo-iroh/rust'), encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] }))
  for (const p of meta.packages) if (p.source) add(p.name, p.version, p.license, 'mobile-app (Rust)')
} catch { console.error('cargo metadata failed: Rust crates not listed') }
// Cargo: the desktop shell (desktop-app/src-tauri; Tauri and its plugins, all platforms).
try {
  const meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], { cwd: path.join(root, 'desktop-app/src-tauri'), encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] }))
  for (const p of meta.packages) if (p.source) add(p.name, p.version, p.license, 'desktop-app (Rust)')
} catch { console.error('cargo metadata failed: desktop crates not listed') }

const byLicense = new Map()
for (const r of rows.values()) {
  if (!byLicense.has(r.license)) byLicense.set(r.license, [])
  byLicense.get(r.license).push(r)
}
const licenses = [...byLicense.keys()].sort((a, b) => byLicense.get(b).length - byLicense.get(a).length)
let out = `# Third-party notices

Hermes UI is MIT-licensed (see [LICENSE](LICENSE)). It uses the open-source components below. The
license texts ship with each package (\`node_modules/<name>/LICENSE\`, the crate sources); this file lists
name, version and license of every production dependency. Generated by \`node scripts/licenses.mjs\`.

Weak copyleft (MPL-2.0): \`web-push\` (backend), UniFFI (bindings of the iroh library), \`attohttpc\`,
\`lightningcss\` (build-time CSS). All are used unmodified; their sources are on npm / crates.io. No
GPL or AGPL code is included (\`node-forge\` is dual-licensed and used under BSD-3-Clause).
\`@getpaseo/*\` declare no license field in package.json; the Paseo project publishes them as
Apache-2.0 (backend only, optional integration).

| License | Packages |
|---|---|
${licenses.map((l) => `| ${l} | ${byLicense.get(l).length} |`).join('\n')}

`
for (const l of licenses) {
  out += `## ${l}\n\n`
  out += byLicense.get(l).sort((a, b) => a.name.localeCompare(b.name)).map((r) => `- ${r.name} ${r.version} (${[...r.where].join(', ')})`).join('\n') + '\n\n'
}
fs.writeFileSync(path.join(root, 'THIRD-PARTY-NOTICES.md'), out)
console.log(`THIRD-PARTY-NOTICES.md: ${rows.size} packages, ${licenses.length} licenses`)
const bad = licenses.filter((l) => /AGPL|(^|[^L])GPL|SSPL|UNKNOWN|UNLICENSED/i.test(l))
if (bad.length) console.log(`check: ${bad.map((l) => `${l} (${byLicense.get(l).map((r) => r.name).join(', ')})`).join('; ')}`)
