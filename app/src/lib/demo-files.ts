const SCRIPT = `// Builds the quarterly Lighthouse report from the staging run.
import { readFile, writeFile } from 'node:fs/promises'

type Row = { page: string; performance: number; accessibility: number; seo: number }

export async function buildReport(csv: string, out: string) {
  const rows: Row[] = (await readFile(csv, 'utf8'))
    .trim().split('\\n').slice(1)
    .map((line) => {
      const [page, performance, accessibility, , seo] = line.split(',')
      return { page, performance: +performance, accessibility: +accessibility, seo: +seo }
    })
  const avg = rows.reduce((s, r) => s + r.performance, 0) / rows.length
  await writeFile(out, JSON.stringify({ pages: rows.length, avg: Math.round(avg) }, null, 2))
  return avg >= 90
}
`
