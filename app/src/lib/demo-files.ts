const keyOf = (path: string) => new URLSearchParams(path.split('?')[1] || '').get('path') || ''
const isFileUrl = (path: string) => path.startsWith(`/api/sessions/${DEMO_FILES_SESSION}/file`)

/** /api/sessions/demo-files/file/text → the JSON the backend sends, or null for other paths. */
export function demoFileText(path: string): { status: number; body: unknown } | null {
  if (!path.startsWith(`/api/sessions/${DEMO_FILES_SESSION}/file/text`)) return null
  const f = byKey(keyOf(path))
  if (!f || f.text === undefined) return { status: 404, body: { error: 'not found' } }
  return { status: 200, body: { text: f.text, truncated: false, size: utf8(f.text).length } }
}

/** Web: a data URL for a preview or download URL of the demo files, or null for other paths. */
export function demoFileUrl(path: string): string | null {
  if (!isFileUrl(path)) return null
  const f = byKey(keyOf(path))
  if (!f) throw new Error('not found')
  if (f.dataUrl) return f.dataUrl
  return `data:${f.mime};base64,${base64(bytesOf(f))}`
}

/** Native: the bytes for a preview or download URL, or null for other paths. */
export function demoFileBytes(path: string): Uint8Array | null {
  if (!isFileUrl(path)) return null
  const f = byKey(keyOf(path))
  return f ? bytesOf(f) : new Uint8Array()
}
