/** A three-page PDF (Helvetica, a title and a few lines per page), offsets computed so viewers accept it. */
function demoPdf(): string {
  const pages = [
    ['Quarterly report Q3', '', 'Landing page: Lighthouse performance 95 on average (was 81).', 'Build time down from 6 to 2 minutes.', 'Two open bugs, both with a fix in review.', '', 'Generated by Hermes in the demo mode.'],
    ['Lighthouse per page', '', '/            performance 97, accessibility 100', '/pricing     performance 94, accessibility 98', '/docs        performance 96, accessibility 100', '/blog        performance 93, accessibility 97', '/contact     performance 99, accessibility 100'],
    ['Next steps', '', 'Lazy-load the testimonial images on /blog.', 'Inline the critical CSS of /pricing.', 'Re-run the report after the next release.'],
  ]
  const text = (lines: string[]) => lines.map((l, i) => `${i === 0 ? '/F1 22 Tf' : '/F1 12 Tf'} 72 ${720 - (i === 0 ? 0 : 20 + i * 18)} Td (${l}) Tj`).map((x) => `BT ${x} ET`).join('\n')
  // 1 catalog, 2 pages, 3 font, then per page: the page and its content stream.
  const kids = pages.map((_, i) => `${4 + 2 * i} 0 R`).join(' ')
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    `<< /Type /Pages /Kids [${kids}] /Count ${pages.length} >>`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    ...pages.flatMap((lines, i) => {
      const t = text(lines)
      return [
        `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents ${5 + 2 * i} 0 R >>`,
        `<< /Length ${t.length} >>\nstream\n${t}\nendstream`,
      ]
    }),
  ]
  let out = '%PDF-1.4\n'
  const offsets: number[] = []
  objs.forEach((o, i) => { offsets.push(out.length); out += `${i + 1} 0 obj\n${o}\nendobj\n` })
  const xref = out.length
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offsets.map((n) => `${String(n).padStart(10, '0')} 00000 n \n`).join('')}`
  out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`
  return out
}

