const utf8 = (s: string) => new TextEncoder().encode(s)
const bytesOf = (f: DemoFile): Uint8Array => {
  if (f.text !== undefined) return utf8(f.text)
  if (f.body) return Uint8Array.from(f.body(), (c) => c.charCodeAt(0))
  const b64 = f.dataUrl!.slice(f.dataUrl!.indexOf(',') + 1)
  return Uint8Array.from(atob(b64), (c) => c.charCodeAt(0))
}
const base64 = (bytes: Uint8Array) => { let s = ''; for (const b of bytes) s += String.fromCharCode(b); return btoa(s) }

